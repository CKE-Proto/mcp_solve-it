"""Generate the badge text width table from the bundled Liberation Sans Bold.

Liberation Sans Bold has the same advance widths as Arial Bold, the font the
SOLVE-IT Explorer measures badge text with. The table covers printable ASCII
plus U+2018/U+2019 (curly single quotes), which is every character used in
current SOLVE-IT item names and ids.

Usage (needs fontTools, e.g. ``uv pip install fonttools``):

    python scripts/gen_badge_widths.py

Writes ``src/mcp_chassis/extensions/badges/widths.py``.
"""

from __future__ import annotations

from pathlib import Path

from fontTools.ttLib import TTFont

_ROOT = Path(__file__).resolve().parent.parent
_BADGES = _ROOT / "src" / "mcp_chassis" / "extensions" / "badges"
_FONT = _BADGES / "fonts" / "LiberationSans-Bold.ttf"
_OUT = _BADGES / "widths.py"

_CODEPOINTS = [*range(0x20, 0x7F), 0x2018, 0x2019]


def main() -> None:
    """Read advance widths from the font and write the Python table."""
    font = TTFont(str(_FONT))
    units_per_em = font["head"].unitsPerEm
    cmap = font.getBestCmap()
    hmtx = font["hmtx"]

    advances: dict[str, int] = {}
    for cp in _CODEPOINTS:
        glyph = cmap[cp]
        advances[chr(cp)] = int(hmtx[glyph][0])

    ascii_units = [advances[chr(cp)] for cp in range(0x20, 0x7F)]
    fallback = round(sum(ascii_units) / len(ascii_units))

    lines = [
        '"""Advance widths for badge text layout (generated, do not edit).',
        "",
        "Generated by ``scripts/gen_badge_widths.py`` from the bundled",
        "Liberation Sans Bold, which is metric-compatible with Arial Bold.",
        "Widths are in font units; a string's width at ``size`` px is",
        "``sum(units) * size / UNITS_PER_EM``.",
        '"""',
        "",
        f"UNITS_PER_EM = {units_per_em}",
        "",
        "# Used for characters missing from ADVANCES (mean of printable ASCII).",
        f"FALLBACK_ADVANCE = {fallback}",
        "",
        "ADVANCES: dict[str, int] = {",
    ]
    for ch, units in advances.items():
        lines.append(f"    {ch!r}: {units},")
    lines.append("}")
    _OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote {len(advances)} widths to {_OUT}")


if __name__ == "__main__":
    main()
